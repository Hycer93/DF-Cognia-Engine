OUT_LOG = None  # 逐轮对话原文（人可读 + 机器可读双份）

def log_round(r: dict):
    with open(OUT_LOG, "a", encoding="utf-8") as f:
        f.write(json.dumps(r, ensure_ascii=False) + "\n")

def ds_chat(llm, msgs):
    """DeepSeek 参与攻防：带浅 persona，纯裸思维（无走链、无图——对照组本色）"""
    for attempt in range(3):
        try:
            r = llm.chat(msgs)
            if r:
                return r
        except Exception:
            time.sleep(2 * attempt + 1)
    return ""

def verify(llm, q, a):
    PROMPT = ("判断这个回答是否真正回应了引导者的问题和质疑（意图贴合），"
              "不要求字面复述。输出严格 JSON: {\"score\": 0.0-1.0, \"note\": \"15字内\"}"
              f"\n引导者输入: {q[:500]}\n回答: {a[:3000]}")
    try:
        r = llm.chat([{"role": "user", "content": PROMPT}])
        j = json.loads(r[r.find("{"):r.rfind("}") + 1])
        return max(0.0, min(1.0, float(j.get("score", 0.5)))), str(j.get("note", ""))[:20]
    except Exception:
        return None, ""


